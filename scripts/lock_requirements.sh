#!/bin/sh
# Regenerate requirements-lock.txt from py_requirements.txt.
#
# The lock pins every package, including transitive ones, so a deploy
# installs the same versions that were tested rather than whatever is
# current on PyPI that day.
#
# It is built in a THROWAWAY virtualenv containing only the production
# requirements. Running `pip freeze` in a development environment instead
# would sweep in pytest, hypothesis, flake8 and anything else installed ad
# hoc, and ship all of it to the server.
#
# Run this whenever py_requirements.txt changes, and commit the result.
#
#     ./scripts/lock_requirements.sh
set -e

here=$(cd "$(dirname "$0")/.." && pwd)
source_file="$here/py_requirements.txt"
lock_file="$here/requirements-lock.txt"

if [ ! -f "$source_file" ]; then
    echo "ERROR: $source_file not found" >&2
    exit 1
fi

tmpdir=$(mktemp -d)
trap 'rm -rf "$tmpdir"' EXIT

echo "Building a clean environment in $tmpdir"
python3 -m venv "$tmpdir/venv"
"$tmpdir/venv/bin/pip" install --quiet --upgrade pip
# --no-cache-dir because a corrupt partial wheel in the local pip cache
# otherwise fails the download with a truncated-read error, repeatably.
"$tmpdir/venv/bin/pip" install --quiet --no-cache-dir --retries 10 \
    --timeout 60 -r "$source_file"

{
    echo "# Generated by scripts/lock_requirements.sh -- do not edit by hand."
    echo "# Pinned versions of py_requirements.txt and everything it pulls in,"
    echo "# captured from a clean environment. Regenerate and commit whenever"
    echo "# py_requirements.txt changes."
    echo "#"
    echo "# Built with $(python3 --version 2>&1) on $(date -u +%Y-%m-%d)"
    "$tmpdir/venv/bin/pip" freeze --exclude-editable | sort -f
} > "$lock_file"

count=$(grep -vc '^#' "$lock_file")
echo "Wrote $lock_file ($count pinned packages)"
